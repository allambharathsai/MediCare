
class Patient {
  final String id;
  final String name;
  final int age;
  final String gender;
  final String phone;
  final String bloodGroup;
  final String department;
  final String doctor;
  final String admissionDate;
  final String status;

  const Patient({
    required this.id,
    required this.name,
    required this.age,
    required this.gender,
    required this.phone,
    required this.bloodGroup,
    required this.department,
    required this.doctor,
    required this.admissionDate,
    required this.status,
  });
}
